import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function formatDate(date: Date | string | null | undefined): string {
  if (!date) return "—";
  const d = new Date(date);
  return d.toLocaleDateString(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

export function formatDateTime(date: Date | string | null | undefined): string {
  if (!date) return "—";
  const d = new Date(date);
  return d.toLocaleString(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function formatMoney(
  amount: number | { toString(): string } | null | undefined,
  currency = "USD",
): string {
  const value =
    typeof amount === "object" && amount !== null
      ? Number(amount)
      : amount === null || amount === undefined
        ? 0
        : Number(amount);
  return new Intl.NumberFormat(undefined, {
    style: "currency",
    currency,
  }).format(value);
}

export function addDays(date: Date, days: number): Date {
  const d = new Date(date);
  d.setDate(d.getDate() + days);
  return d;
}

export function toISODate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

export function fromISODate(iso: string): Date {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, (m ?? 1) - 1, d ?? 1);
}

export interface RoomLikeDisplay {
  number?: string | null;
  name?: string | null;
  roomType?: { name?: string | null } | null;
  property?: { name?: string | null } | null;
}

/**
 * Returns a clean, human-readable display name for any room or unit.
 * Strips legacy placeholder names like "MAIN" or "Room MAIN", prioritizing
 * real room names, listing titles, and unit names.
 */
export function formatRoomDisplayName(room?: RoomLikeDisplay | null): string {
  if (!room) return "Unassigned";

  const num = (room.number ?? "").trim();
  const rawName = (room.name ?? "").trim();
  // Strip trailing " MAIN" if generated by legacy bulk importer or default single-unit naming
  const cleanName = rawName.replace(/[\s_-]+MAIN$/i, "").trim();

  const isMainPlaceholder = num.toUpperCase() === "MAIN" || !num;

  // If number is "MAIN" or empty, always prefer cleanName, then property or roomType name
  if (isMainPlaceholder) {
    if (cleanName && cleanName.toUpperCase() !== "MAIN") return cleanName;
    if (room.property?.name) return room.property.name;
    if (room.roomType?.name && room.roomType.name !== "Entire Property") return room.roomType.name;
    return "Main Unit";
  }

  // If cleanName exists and is distinct from num
  if (cleanName && cleanName.toLowerCase() !== num.toLowerCase()) {
    // If cleanName already includes the number (e.g. "Villa 101" vs "101"), display cleanName
    if (cleanName.toLowerCase().includes(num.toLowerCase())) {
      return cleanName;
    }
    // E.g. "101 · Deluxe Ocean Suite"
    return `${num} · ${cleanName}`;
  }

  if (cleanName) return cleanName;

  // If num already starts with "Room", "Unit", "Suite", "Villa", "Apt", "Cabin", return directly
  if (/^(room|unit|suite|villa|apt|cabin)\b/i.test(num)) {
    return num;
  }

  // Purely numeric or short code like "101" or "202"
  if (/^\d+[a-zA-Z]?$/.test(num)) {
    return `Room ${num}`;
  }

  return num;
}

